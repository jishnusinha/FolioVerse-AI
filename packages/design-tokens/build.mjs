import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export function buildTokens(tokens) {
  const v = (name, value) => `--fv-${name}:${value};`;
  const base = [];
  for (const [k, val] of Object.entries(tokens.font)) base.push(v(`font-${k}`, val));
  for (const [k, val] of Object.entries(tokens.fs)) base.push(v(`fs-${k}`, val));
  for (const [k, val] of Object.entries(tokens.s)) base.push(v(`s-${k}`, val));
  for (const [k, val] of Object.entries(tokens.r)) base.push(v(`r-${k}`, val));
  for (const [k, val] of Object.entries(tokens.layout)) base.push(v(k, val));
  for (const [k, val] of Object.entries(tokens.motion)) base.push(v(k, val));
  const light = Object.entries(tokens.color.light).map(([k, val]) => v(k, val));
  const lightShadow = Object.entries(tokens.shadow.light).map(([k, val]) => v(`shadow-${k}`, val));
  const dark = Object.entries(tokens.color.dark).map(([k, val]) => v(k, val));
  const darkShadow = Object.entries(tokens.shadow.dark).map(([k, val]) => v(`shadow-${k}`, val));
  const studio = Object.entries(tokens.color.studio).map(([k, val]) => v(k, val));

  const css =
    `/* Generated by @folioverse/design-tokens. Do not edit. */\n` +
    `:root{\n${[...base, ...light, ...lightShadow].join('\n')}\n}\n` +
    `[data-theme=dark],.studio{\n${[...dark, ...darkShadow].join('\n')}\n}\n` +
    `.studio{\n${studio.join('\n')}\nbackground:var(--fv-bg);color:var(--fv-text);\n}\n`;

  const colorNames = Object.keys(tokens.color.light);
  const theme =
    `/* Generated by @folioverse/design-tokens. Tailwind v4 theme bound to --fv-* variables. */\n` +
    `@theme inline {\n` +
    colorNames.map((n) => `  --color-fv-${n}: var(--fv-${n});`).join('\n') +
    `\n  --font-sans: var(--fv-font-sans);\n  --font-serif: var(--fv-font-serif);\n  --font-mono: var(--fv-font-mono);\n` +
    Object.keys(tokens.r).map((k) => `  --radius-fv-${k}: var(--fv-r-${k});`).join('\n') +
    `\n` +
    Object.keys(tokens.shadow.light).map((k) => `  --shadow-fv-${k}: var(--fv-shadow-${k});`).join('\n') +
    `\n}\n`;

  const js =
    `// Generated by @folioverse/design-tokens. Do not edit.\n` +
    `export const tokens = ${JSON.stringify(tokens, null, 2)};\n` +
    `export const cssVar = (name) => \`var(--fv-\${name})\`;\n` +
    `export default tokens;\n`;
  return { css, theme, js };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
  const out = buildTokens(tokens);
  mkdirSync(join(here, 'dist'), { recursive: true });
  writeFileSync(join(here, 'dist/tokens.css'), out.css);
  writeFileSync(join(here, 'dist/tailwind.css'), out.theme);
  writeFileSync(join(here, 'dist/tokens.js'), out.js);
  console.log('design-tokens: wrote dist/tokens.css, dist/tailwind.css, dist/tokens.js');
}
