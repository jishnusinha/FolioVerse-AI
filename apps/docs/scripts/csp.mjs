// Postbuild: hashes Starlight's inline <script> blocks in dist/ and writes csp/docs-csp.caddy, which the web
// image's Caddyfile imports inside `handle /docs/*` to replace the app CSP for the documentation site.
// Pagefind search compiles WebAssembly, hence 'wasm-unsafe-eval'; no 'unsafe-inline' scripts are allowed.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Inline script bodies of an HTML document (scripts with `src` are covered by 'self'). */
export function inlineScripts(html) {
  return [...html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/g)]
    .filter((m) => !/\ssrc=/.test(m[1] ?? '') && !/type="application\/(ld\+)?json"/.test(m[1] ?? ''))
    .map((m) => m[2]);
}

export const sha256 = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

export function policy(hashes) {
  return [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' ${[...hashes].sort().join(' ')}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self' data:",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? htmlFiles(join(dir, e.name)) : e.name.endsWith('.html') ? [join(dir, e.name)] : [],
  );
}

export function buildPolicy(distDir) {
  const hashes = new Set();
  for (const file of htmlFiles(distDir)) for (const s of inlineScripts(readFileSync(file, 'utf8'))) hashes.add(sha256(s));
  return { hashes, csp: policy(hashes) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { hashes, csp } = buildPolicy(join(APP, 'dist'));
  const out = join(APP, 'csp/docs-csp.caddy');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `# Generated by apps/docs/scripts/csp.mjs from the built pages. Do not edit.\nheader Content-Security-Policy "${csp}"\n`);
  console.log(`docs: CSP with ${hashes.size} inline script hashes written to csp/docs-csp.caddy`);
}
